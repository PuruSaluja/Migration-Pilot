"""P2-13 (SPEC FR-3, decisions D1): 15 labelled detection fixtures, 8 Node and 7 Python.

Each fixture is a small repository tree, written to look like a common real-world shape, plus a
label: what a person reading the repo would say its test command, package manager and runtime
are. **The labels were written from how such projects really run their tests, before the
detector was run on any of them**, and the tests that score them never import a label from the
detector. If a fixture fails, the result is reported as it is: either the detector is wrong
(fix it, with a test) or the label was (fix it, and say so in PROGRESS.md). A fixture is never
reshaped to make the number pass.

These are reconstructions of common shapes, not copies of real repositories, so the score
measures the detector on those shapes. It is not a claim about the accuracy on arbitrary repos.

Labels use the command conventions of this tool (§9.4): commands run with `sh -c` from the
repository root, Python tools through the venv the install step creates (`.venv/bin/python`).
`None` in a label means "not labelled" for that field (install commands for Python are
long shell lines; they are checked through the package manager instead).
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field

from mpilot.models.domain import Ecosystem

PY_TEST = ".venv/bin/python -m pytest -q"
PY_UNITTEST = ".venv/bin/python -m unittest discover"


@dataclass(frozen=True)
class Label:
    test_cmd: str
    package_manager: str
    runtime_version: str
    install_cmd: str | None = None
    typecheck_cmd: str | None = None
    build_cmd: str | None = None


@dataclass(frozen=True)
class Fixture:
    name: str
    ecosystem: Ecosystem
    shape: str  # one line: what real-world shape this stands for
    files: dict[str, str]
    label: Label
    ecosystem_hint: bool = False  # pass the ecosystem explicitly (repos with both kinds of files)
    notes: list[str] = field(default_factory=list)


def pkg(**fields: object) -> str:
    return json.dumps({"name": "example", "version": "1.0.0", **fields}, indent=2)


